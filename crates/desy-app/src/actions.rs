//! Keyboard actions and shortcuts. `secondary` below means ⌘ on macOS and Ctrl elsewhere.

use gpui_kit::{App, KeyBinding, actions};

actions!(
    desy,
    [
        Undo,
        Redo,
        Save,
        SaveAs,
        ExportSvg,
        CloseProject,
        ToggleSnap,
        ZoomIn,
        ZoomOut,
        ZoomFit,
        Zoom100,
        Union,
        Subtract,
        Intersect,
        Exclude,
        Delete,
        Duplicate,
        Copy,
        Cut,
        Paste,
        SelectAll,
        Cancel,
        Confirm,
        BringForward,
        SendBackward,
        BringToFront,
        SendToBack,
        NudgeLeft,
        NudgeRight,
        NudgeUp,
        NudgeDown,
        NudgeLeftBig,
        NudgeRightBig,
        NudgeUpBig,
        NudgeDownBig,
        ToolSelect,
        ToolDirect,
        ToolPen,
        ToolPencil,
        ToolLine,
        ToolRect,
        ToolEllipse,
        ToolPolygon,
        ToolStar,
        ToolWave,
        ToolBlob,
        ToolText,
        ToolWidth,
        ToolHand,
        ToolMirror,
        ToolEyedropper,
        ImportImage,
        FlipHorizontal,
        FlipVertical,
        Quit
    ]
);

fn key<A: gpui_kit::Action>(keys: &str, action: A, context: Option<&str>) -> KeyBinding {
    let primary = if cfg!(target_os = "macos") { "cmd" } else { "ctrl" };
    // Bindings are created once at startup; leaking the few strings is fine.
    let keys: &'static str = Box::leak(keys.replace("secondary", primary).into_boxed_str());
    KeyBinding::new(keys, action, context)
}

pub fn bind_keys(cx: &mut App) {
    let editor = Some("Editor");
    let canvas = Some("Canvas");
    cx.bind_keys([
        key("secondary-q", Quit, None),
        key("secondary-s", Save, editor),
        key("secondary-shift-s", SaveAs, editor),
        key("secondary-e", ExportSvg, editor),
        key("secondary-i", ImportImage, editor),
        key("secondary-w", CloseProject, editor),
        key("secondary-;", ToggleSnap, editor),
        key("secondary-=", ZoomIn, editor),
        key("secondary-+", ZoomIn, editor),
        key("secondary--", ZoomOut, editor),
        key("secondary-0", ZoomFit, editor),
        key("secondary-1", Zoom100, editor),
        key("secondary-alt-u", Union, editor),
        key("secondary-alt-s", Subtract, editor),
        key("secondary-alt-i", Intersect, editor),
        key("secondary-alt-x", Exclude, editor),
        // Canvas-only: these keys must keep typing text inside inputs.
        key("secondary-z", Undo, canvas),
        key("secondary-shift-z", Redo, canvas),
        key("secondary-y", Redo, canvas),
        key("backspace", Delete, canvas),
        key("delete", Delete, canvas),
        key("secondary-d", Duplicate, canvas),
        key("secondary-c", Copy, canvas),
        key("secondary-x", Cut, canvas),
        key("secondary-v", Paste, canvas),
        key("secondary-a", SelectAll, canvas),
        key("escape", Cancel, canvas),
        key("enter", Confirm, canvas),
        key("secondary-]", BringForward, canvas),
        key("secondary-[", SendBackward, canvas),
        key("secondary-shift-]", BringToFront, canvas),
        key("secondary-shift-[", SendToBack, canvas),
        key("left", NudgeLeft, canvas),
        key("right", NudgeRight, canvas),
        key("up", NudgeUp, canvas),
        key("down", NudgeDown, canvas),
        key("shift-left", NudgeLeftBig, canvas),
        key("shift-right", NudgeRightBig, canvas),
        key("shift-up", NudgeUpBig, canvas),
        key("shift-down", NudgeDownBig, canvas),
        key("v", ToolSelect, canvas),
        key("a", ToolDirect, canvas),
        key("p", ToolPen, canvas),
        key("n", ToolPencil, canvas),
        key("l", ToolLine, canvas),
        key("m", ToolRect, canvas),
        key("r", ToolRect, canvas),
        key("e", ToolEllipse, canvas),
        key("o", ToolEllipse, canvas),
        key("y", ToolPolygon, canvas),
        key("s", ToolStar, canvas),
        key("u", ToolWave, canvas),
        key("b", ToolBlob, canvas),
        key("t", ToolText, canvas),
        key("w", ToolWidth, canvas),
        key("shift-w", ToolWidth, canvas),
        key("h", ToolHand, canvas),
        key("x", ToolMirror, canvas),
        key("i", ToolEyedropper, canvas),
        key("shift-h", FlipHorizontal, canvas),
        key("shift-v", FlipVertical, canvas),
    ]);
}
